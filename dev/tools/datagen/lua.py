"""Writes Lua values for the data packs: compact, sorted, always the same text
for the same data (so a new build only changes the lines that really changed)."""


def string(value):
    out = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return '"%s"' % out


def value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return string(v)
    raise TypeError("no Lua form for %r" % (v,))


def row(values):
    return "{ %s }" % ", ".join(value(v) for v in values)


def header(title, version, date, sources):
    lines = [
        "-- MapScout data pack for WoW Forever: %s." % title,
        "-- Generated by dev/tools/datagen from build %s%s. Do not edit." % (version, " (%s)" % date if date else ""),
    ]
    for source in sources:
        lines.append("-- Source: %s" % source)
    return "\n".join(lines) + "\n"
